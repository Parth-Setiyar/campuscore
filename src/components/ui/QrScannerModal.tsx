import { useEffect, useId, useRef, useState } from 'react';
import { Html5Qrcode } from 'html5-qrcode';
import { Camera, AlertCircle, Upload } from 'lucide-react';
import { Modal } from './CommonUi';

interface QrScannerModalProps {
  open: boolean;
  onClose: () => void;
  onScanSuccess: (decodedText: string) => void;
}

export function QrScannerModal({ open, onClose, onScanSuccess }: QrScannerModalProps) {
  const elementId = useId().replace(/:/g, '');
  const scannerRef = useRef<Html5Qrcode | null>(null);
  const [cameraError, setCameraError] = useState<string | null>(null);
  const [scanning, setScanning] = useState(false);

  useEffect(() => {
    if (!open) return;

    let cancelled = false;
    setCameraError(null);

    const startScanner = async () => {
      try {
        const scanner = new Html5Qrcode(`qr-reader-${elementId}`);
        scannerRef.current = scanner;
        setScanning(true);
        await scanner.start(
          { facingMode: 'environment' },
          { fps: 10, qrbox: { width: 220, height: 220 } },
          (decodedText) => {
            if (!cancelled) {
              scanner
                .stop()
                .catch(() => {})
                .finally(() => {
                  scannerRef.current = null;
                  onScanSuccess(decodedText);
                  onClose();
                });
            }
          },
          () => {
            // Frame scan error ignored while searching
          }
        );
      } catch (err: unknown) {
        if (!cancelled) {
          setScanning(false);
          const msg =
            err instanceof Error
              ? err.message
              : 'Camera access was denied or unavailable on this device.';
          setCameraError(
            `${msg} You can upload a QR code image below or paste the invitation code directly.`
          );
        }
      }
    };

    const timer = window.setTimeout(startScanner, 150);

    return () => {
      cancelled = true;
      window.clearTimeout(timer);
      if (scannerRef.current) {
        const instance = scannerRef.current;
        scannerRef.current = null;
        instance.stop().catch(() => {});
      }
    };
  }, [open, elementId, onClose, onScanSuccess]);

  const handleFileUpload = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    setCameraError(null);
    try {
      const scanner = scannerRef.current ?? new Html5Qrcode(`qr-reader-${elementId}`);
      const decoded = await scanner.scanFile(file, true);
      onScanSuccess(decoded);
      onClose();
    } catch {
      setCameraError('Could not detect a valid QR code in the uploaded image.');
    }
  };

  return (
    <Modal
      open={open}
      onClose={onClose}
      title="Scan Class Invitation QR"
      description="Point your device camera at the class QR code generated by the HOD, or upload a QR image."
      maxWidthClass="max-w-md"
    >
      <div className="space-y-4">
        <div className="overflow-hidden rounded-xl border border-[#E4E5ED] bg-[#F3F4F8]">
          <div id={`qr-reader-${elementId}`} className="min-h-[260px] w-full" />
        </div>

        {scanning && !cameraError && (
          <div className="flex items-center gap-2 text-xs text-[#777D91]">
            <Camera className="h-3.5 w-3.5 text-[#5146D8]" />
            <span>Camera active. Align the invitation QR code inside the frame.</span>
          </div>
        )}

        {cameraError && (
          <div className="flex items-start gap-2.5 rounded-xl border border-[#D99A32]/30 bg-[#D99A32]/8 p-3 text-xs text-[#20243A]">
            <AlertCircle className="mt-0.5 h-4 w-4 shrink-0 text-[#D99A32]" />
            <span>{cameraError}</span>
          </div>
        )}

        <div className="flex items-center justify-between border-t border-[#E4E5ED] pt-3">
          <label className="inline-flex cursor-pointer items-center gap-2 rounded-xl border border-[#E4E5ED] bg-white px-3.5 py-2 text-xs font-medium text-[#20243A] transition-colors hover:bg-[#F3F4F8]">
            <Upload className="h-3.5 w-3.5 text-[#5146D8]" />
            <span>Scan QR from Image</span>
            <input type="file" accept="image/*" onChange={handleFileUpload} className="hidden" />
          </label>
          <button
            type="button"
            onClick={onClose}
            className="rounded-xl border border-[#E4E5ED] px-3.5 py-2 text-xs font-medium text-[#777D91] hover:bg-[#F3F4F8] hover:text-[#20243A]"
          >
            Close
          </button>
        </div>
      </div>
    </Modal>
  );
}
